import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { catalogSourceDigests } from '../src/content/catalog-source-digests.ts';

const root = resolve(import.meta.dirname, '..');
const excluded = new Set([
  'src/content/catalog-source-digests.ts', // generated output
  'src/content/catalog-release-decision.ts', // signed decision cannot hash itself
]);
const roots = ['src', 'public', '.gitattributes', 'package.json', 'package-lock.json', 'next.config.ts', 'postcss.config.mjs', 'tsconfig.json', 'wrangler.jsonc',
  'open-next.config.ts', '.github/workflows/deploy.yml',
  'scripts/catalog-source-coverage.mjs', 'scripts/catalog-review-digest.mjs', 'scripts/product-catalog-check.mjs', 'scripts/product-review-digest.mjs'];
const files = [];
function walk(path) {
  const absolute = join(root, path);
  const stat = readdirSync(absolute, { withFileTypes: true });
  for (const item of stat) {
    const next = `${path}/${item.name}`.replaceAll('\\', '/');
    if (item.isDirectory()) walk(next);
    else if (item.isFile() && !excluded.has(next)) files.push(next);
  }
}
for (const path of roots) {
  if (path.includes('.')) files.push(path);
  else walk(path);
}
const current = Object.fromEntries(files.sort().map((path) => [path, createHash('sha256').update(readFileSync(join(root, path))).digest('hex')]));
if (process.argv.includes('--write')) {
  writeFileSync(join(root, 'src/content/catalog-source-digests.ts'), `/** Generated by scripts/catalog-source-coverage.mjs --write; checked on every build. */\nexport const catalogSourceDigests: Readonly<Record<string, string>> = ${JSON.stringify(current, null, 2)};\n`);
  console.log(`Recorded ${files.length} catalogue-affecting source and image files.`);
} else if (JSON.stringify(current) !== JSON.stringify(catalogSourceDigests)) {
  const changed = [...new Set([...Object.keys(current), ...Object.keys(catalogSourceDigests)])]
    .filter((path) => current[path] !== catalogSourceDigests[path]);
  console.error(`Catalog source coverage is stale: ${changed.join(', ')}. Recompute before review; existing catalog approval must remain invalid.`);
  process.exitCode = 1;
} else {
  console.log(`Catalog source coverage: ${files.length} files match.`);
}
