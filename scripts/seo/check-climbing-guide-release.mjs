import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const read = path => readFileSync(path);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const archive = 'docs/seo/content/g9-review-v1';
const release = JSON.parse(read('docs/seo/g9-release.json'));
const module = read('src/content/seo/climbing-guide.ts').toString();
const guide = JSON.parse(module.match(/export const climbingGuide = (\{[\s\S]*?\}) as const;/)[1]);
const assets = JSON.parse(module.match(/export const climbingAssets = (\{[\s\S]*?\}) as const;/)[1]);
const embeddedRelease = JSON.parse(module.match(/export const climbingRelease = (\{[\s\S]*?\}) as const;/)[1]);
assert.deepEqual(embeddedRelease, release);
assert.equal(hash(read(`${archive}/article.en.md`)), release.sourceSha256);
assert.equal(guide.bodyMarkdown, read(`${archive}/article.en.md`).toString());
assert.equal(guide.sourceSha256, release.sourceSha256);
assert.equal(hash(read(`${archive}/assets.json`)), release.assetsSha256);
assert.deepEqual(assets, JSON.parse(read(`${archive}/assets.json`)));
for (const asset of Object.values(assets)) assert.equal(hash(read(`public${asset.src}`)), asset.sha256, asset.src);
const metadata = JSON.parse(read(`${archive}/metadata.json`));
assert.equal(guide.seoTitle, metadata.title);
assert.equal(guide.metaDescription, metadata.description);
assert.equal(guide.path, metadata.path);
assert.deepEqual(guide.citations, metadata.citations);
const review = JSON.parse(read(`${archive}/review-manifest.json`));
assert.equal(release.reviewPackageDigest, review.packageDigest);
assert.equal(release.version, 'G9 V1.1');
assert.equal(release.authorizationText, '发布吧');
assert.ok(Number.isFinite(Date.parse(release.publishedAt)));
assert.ok(read(release.decisionRef).toString().includes(release.reviewPackageDigest));
console.log('G9 V1.1: approved body, metadata, four image bytes and release receipt match.');
