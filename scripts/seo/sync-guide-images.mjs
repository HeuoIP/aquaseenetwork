import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../..');
const source = resolve(root, 'scripts/seo/guide-image-sources.json');
const target = resolve(root, 'src/content/seo/guide-image-manifest.generated.ts');
const files = JSON.parse(readFileSync(source, 'utf8'));
const expectedSlots = ['cover', 'zones', 'material'];
if (JSON.stringify(Object.keys(files)) !== JSON.stringify(expectedSlots)) {
  throw new Error('Guide image sources must contain cover, zones and material in that order.');
}

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const manifest = {};
for (const slot of expectedSlots) {
  const { sourceFile, derivativeFile } = files[slot];
  if (!sourceFile.startsWith('docs/previews/wp-seo-02/') || !derivativeFile.startsWith('public/images/')) {
    throw new Error(`Unexpected guide asset location for ${slot}.`);
  }
  manifest[slot] = {
    sourceFile,
    sourceSha256: sha256(readFileSync(resolve(root, sourceFile))),
    src: `/${derivativeFile.slice('public/'.length)}`,
    webpSha256: sha256(readFileSync(resolve(root, derivativeFile))),
  };
}
const imageManifestSha256 = sha256(JSON.stringify(manifest));
const output = `/** Generated by scripts/seo/sync-guide-images.mjs from current source and public image bytes. */\nexport const poolSlideGuideImages = ${JSON.stringify({ ...manifest, imageManifestSha256 }, null, 2)} as const;\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('Guide image sources, public files and release manifest differ. Review and regenerate before building. Existing image approval is invalid.');
    process.exitCode = 1;
  } else {
    console.log(`Guide image manifest matches 3 source/derivative pairs: ${imageManifestSha256}`);
  }
} else if (process.argv.includes('--write')) {
  writeFileSync(target, output);
  console.log(`Recorded guide image manifest: ${imageManifestSha256}`);
} else {
  console.error('Use --check or --write.');
  process.exitCode = 2;
}
